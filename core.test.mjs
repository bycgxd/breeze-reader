import assert from 'node:assert/strict';
import { cleanText, splitText, validateEndpoint, voiceFor, asWav, sentenceSpans, readingSpans, sentenceVoice, applyVoiceCatalog } from './core.mjs';
assert.equal(validateEndpoint('http://localhost:8080'), 'http://localhost:8080/v1/audio/speech');
assert.equal(validateEndpoint('http://host.docker.internal:8080/v1/audio/speech'), 'http://host.docker.internal:8080/v1/audio/speech');
assert.equal(validateEndpoint('http://localhost:8080/v1/'), 'http://localhost:8080/v1/audio/speech');
assert.throws(() => validateEndpoint('javascript:alert(1)'));
assert.throws(() => validateEndpoint('http://user:password@localhost:8080'));
assert.equal(cleanText('<think>不要朗读</think><p>你好，世界。</p>\n```html\n<script>code</script>\n```'), '你好，世界。');
assert.equal(cleanText('<analysis>unfinished'), '');
assert.equal(cleanText('![图片](image.png) [欢迎](https://example.com) **今天晴天**'), '欢迎 今天晴天');
const long = '春天来了。'.repeat(1000) + '🌸';
const chunks = splitText(long);
assert.equal(chunks.join(''), long);
assert(chunks.every(chunk => Array.from(chunk).length <= 2000));
assert.deepEqual(splitText('春风'.repeat(55)+'。'),['春风'.repeat(55)+'。']);
assert.deepEqual(splitText(''), []);
const speech='你好。今天过得怎么样？\n我们一起出去吧！';
assert.deepEqual(readingSpans(speech,'dialogue').map(s=>s.text),['你好。今天过得怎么样？ 我们一起出去吧！']);
assert.deepEqual(readingSpans('（别着急。再想想。）','thought').map(s=>s.text),['（别着急。再想想。）']);
assert.equal(readingSpans(speech,'narration').length,3);
assert.deepEqual(readingSpans('   ','thought'),[]);
const padded='  '+speech+'  ',span=readingSpans(padded,'dialogue')[0];
assert.equal(padded.slice(span.start,span.end),speech);
const utterance='第一句。'.repeat(70);
assert.deepEqual(splitText(utterance),[utterance],'A normal full utterance must use one synthesis request');
assert.equal(voiceFor({voice:'a',characterVoices:{Alice:'b'}}, 'Alice'), 'b');
assert.equal(voiceFor({voice:'a',characterVoices:{}}, 'Bob'), 'a');
const wav = new Blob(['RIFF', new Uint8Array(4), 'WAVE', new Uint8Array(32)], {type:'audio/mpeg'});
assert.equal((await asWav(wav)).type, 'audio/wav');
await assert.rejects(asWav(new Blob(['{"error":"offline"}'])));
const paragraph = '  你好。你好！\n价格是3.14元。🌸今天晴天。';
const sentences = sentenceSpans(paragraph);
assert.deepEqual(sentences.map(s=>s.text),['你好。','你好！','价格是3.14元。','🌸今天晴天。']);
assert(sentences.every(s=>paragraph.slice(s.start,s.end) === s.text));
assert.equal(sentenceVoice({narrator:'n',voices:{alice:'a'}},{kind:'narration'},'f'),'n');
assert.equal(sentenceVoice({voices:{alice:'a'}},{kind:'thought',speakerKey:'Alice'},'f'),'a');
assert.equal(sentenceVoice({thought:'t',voices:{alice:'a'}},{kind:'thought',speakerKey:'Alice'},'f'),'t');
assert.equal(sentenceVoice({voices:{}},{kind:'dialogue',speakerKey:'unknown'},'f'),'f');
assert.equal(sentenceVoice({voices:{}},{kind:'dialogue',speakerKey:'__proto__'},'f'),'f');
assert.equal(sentenceVoice({mode:'single',narrator:'n',thought:'t',voices:{alice:'a'}},{kind:'narration'},'f'),'f');
assert.equal(sentenceVoice({mode:'single',voices:{alice:'a'}},{kind:'dialogue',speakerKey:'Alice'},'f'),'f');
assert.equal(sentenceVoice({mode:'multi',voices:{alice:'a'}},{kind:'dialogue',speakerKey:' Alice '},'f'),'a');
const catalogConfig={voice:'old-voice',voices:['old-voice'],voiceLabels:{'old-voice':'温暖'},characterVoices:{card:'old-voice'},profiles:{card:{mode:'multi',defaultVoice:'old-voice',narrator:'old-voice',thought:'old-voice',voices:{alice:'old-voice'}}}};
applyVoiceCatalog(catalogConfig,[{id:'brv_stable',name:'轩轩',revision:'hash',aliases:['old-voice']}]);
assert.equal(catalogConfig.voice,'brv_stable');assert.equal(catalogConfig.profiles.card.voices.alice,'brv_stable');assert.equal(catalogConfig.profiles.card.narrator,'brv_stable');assert.equal(catalogConfig.characterVoices.card,'brv_stable');assert.equal(catalogConfig.voiceLabels.brv_stable,'温暖');
applyVoiceCatalog(catalogConfig,[{id:'brv_stable',name:'新中文名',revision:'hash',aliases:['新中文名']}]);
assert.equal(catalogConfig.voiceNames.brv_stable,'新中文名');assert.equal(catalogConfig.profiles.card.voices.alice,'brv_stable');assert.equal(catalogConfig.profiles.card.mode,'multi');
const renamedConfig={voice:'english_name',voiceRevisions:{english_name:'100:123'},profiles:{card:{narrator:'english_name',voices:{alice:'english_name'}}}};
const legacyAliases=applyVoiceCatalog(renamedConfig,[{id:'brv_chinese',name:'中文名',revision:'newhash',legacyRevision:'100:123',aliases:['中文名']}]);
assert.equal(legacyAliases.get('english_name'),'brv_chinese');
assert.equal(renamedConfig.voice,'brv_chinese');assert.equal(renamedConfig.profiles.card.voices.alice,'brv_chinese');
console.log('轻声：文本清理、分段、地址与音色映射检查通过');
