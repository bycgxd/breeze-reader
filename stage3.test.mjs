import assert from 'node:assert/strict';
import {audioKey,createAudioCache} from './cache.mjs';
import {waitForStableReport} from './automation.mjs';
let warnings=0;
const cache=createAudioCache('neutral',{storage:null,limit:6,onWarning(){warnings++;}});
await cache.put('a','chat1',new Blob(['1234']));
assert.equal(await (await cache.get('a','chat2')).text(),'1234');
await cache.clear('chat1');assert(await cache.get('a','chat2'));
await cache.clear('chat2');assert.equal(await cache.get('a','chat2'),undefined);
const old=cache.epoch;await cache.clear();await cache.put('old','chat',new Blob(['12']),old);assert.equal((await cache.stats()).count,0);
await cache.put('a','chat',new Blob(['1234']));await new Promise(r=>setTimeout(r,5));await cache.put('b','chat',new Blob(['5678']));
assert.equal(await cache.get('a','chat'),undefined);assert.equal((await cache.stats()).bytes,4);assert.equal(warnings,1);
await cache.put('huge','chat',new Blob(['1234567']));assert.equal((await cache.stats()).count,1);
assert.notEqual(await audioKey('http://a','v','x'),await audioKey('http://a','v2','x'));
assert.notEqual(await audioKey('http://a','v','x'),await audioKey('http://a','v','y'));
assert.notEqual(await audioKey('http://a','v','x'),await audioKey('http://b','v','x'));
Object.defineProperty(crypto,'subtle',{value:undefined,configurable:true});
assert.notEqual(await audioKey('http://a','v','x'),await audioKey('http://a','v','y'),'LAN HTTP exact keys must remain distinct');
delete crypto.subtle;
const ctrl=new AbortController();let ready=false;setTimeout(()=>{ready=true;},5);
const report=await waitForStableReport(()=>({blocks:ready?['visible']:[],loadingFrames:0,inaccessibleFrames:0}),JSON.stringify,ctrl.signal,{interval:2,stableMs:4,timeout:100});assert.deepEqual(report.blocks,['visible']);
const aborted=waitForStableReport(()=>({blocks:[]}),JSON.stringify,ctrl.signal,{interval:2});ctrl.abort();await assert.rejects(aborted,{name:'AbortError'});
await assert.rejects(waitForStableReport(()=>({blocks:[],loadingFrames:1}),JSON.stringify,new AbortController().signal,{interval:2,timeout:8}),/尚未稳定/);
console.log('Stage 3: cache fallback, ownership, capacity, clear race, keys and automation checks passed');
